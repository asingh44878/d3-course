document.querySelector(".turnRed").addEventListener("click", function () {
  document.getElementById("text").style.color = "red";
});

document.querySelector(".turnBlack").addEventListener("click", function () {
  document.getElementById("text").style.color = "#000000";
});

document.querySelector(".turnBlue").addEventListener("click", function () {
  document.getElementById("text").style.color = "blue";
});
